/**
 * Near-optimal rings per form, hill-climbed by `sim/generateNearOptimal.ts`.
 * Elegy, ward and benediction (`NET_OPTIMIZED_FORMS`) are climbed against
 * net — manifestation minus toll — at level 5, 10 rings each: they are not
 * "spend under a budget" forms, so a toll cap either never binds (ward and
 * benediction settle with `measure`, which never charges a toll) or hides
 * the tradeoff (elegy will blow past any cap on doubled losses rather than
 * give up a source, since manifestation-under-a-cap does not charge it for
 * doing so). Every other form is climbed once per caster level for the most
 * manifestation a ring can deliver while keeping toll under that level's cap
 * (5 at level 1, scaling to 15 at level 5) — 10 rings per level, 50 per form
 * — and a climb that never gets under the cap is dropped rather than
 * reported. Every ring honors law 5 throughout the climb (each material
 * once, at most one source), so each is one a player could actually place
 * with `placeComponent`. Regenerate by re-running the generator when the
 * catalog changes shape enough that the frontier might have moved — do not
 * hand-edit the placements below.
 */
import type { CasterLevel, SpellForm } from '../src/types/worldbuilding'

/** Climbed against net rather than a toll cap — see the module doc above. */
export const NET_OPTIMIZED_FORMS: SpellForm[] = ["elegy","ward","benediction"]

export interface NearOptimalRing {
  form: SpellForm
  /** The caster level this ring was climbed and resolved at. */
  level: CasterLevel
  /** Manifestation delivered under this ring's own form and level, at the climb's objective. */
  manifestation: number
  /** Toll paid for the same ring. For a form in `NET_OPTIMIZED_FORMS` this is whatever
   * net asked to pay; otherwise it is always under that level's toll cap. */
  toll: number
  placements: { slotIndex: number; component: string }[]
}

